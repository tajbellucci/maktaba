let LANG = localStorage.getItem("maktaba-lang") || "ur";

function t(key) {
  return (STRINGS[LANG] && STRINGS[LANG][key]) || STRINGS.ur[key] || key;
}

function applyLang() {
  document.documentElement.setAttribute("data-lang", LANG);
  document.documentElement.dir = LANG === "en" ? "ltr" : "rtl";
  document.documentElement.lang = LANG;
  document.body.classList.toggle("lang-ar", LANG === "ar");
  document.querySelectorAll("[data-t]").forEach((el) => {
    el.textContent = t(el.dataset.t);
  });
  document.querySelectorAll("[data-t-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.tPh);
  });
  document.querySelectorAll("[data-t-opt]").forEach((el) => {
    el.textContent = t(el.dataset.tOpt);
  });
  document.querySelectorAll("[data-tip]").forEach((el) => {
    el.title = t(el.dataset.tip);
  });
  const lbl = document.getElementById("langLabel");
  if (lbl) lbl.textContent = t("langSelf");
  /* Was hardcoded to only ever pick between the Urdu and Arabic control-panel
     words, so an English install still got an Urdu/Arabic window title no
     matter what. Now it is a real translated string like everything else. */
  document.title = t("appName") + " — " + t("controlPanel");

  /* refreshMasterUI() is what sets the reader/master badge text, and it only
     runs on login state changes — not on a language switch — so the badge
     was staying frozen in whichever language was active when it was last
     drawn. Only meaningful if the app has already booted (refreshMasterUI is
     defined in app.js, loaded after this file). */
  if (typeof refreshMasterUI === "function") refreshMasterUI();
}

function setLang(next) {
  LANG = next;
  localStorage.setItem("maktaba-lang", LANG);
  applyLang();
  if (typeof renderAll === "function") renderAll();
}
